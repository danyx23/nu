#!/usr/bin/env bash
set -euo pipefail

log() {
  printf '\n==> %s\n' "$*"
}

run_git_pull() {
  local dir="$1"
  if [[ -d "$dir/.git" ]]; then
    log "Updating $dir"
    git -C "$dir" pull --ff-only
  else
    log "Skipping $dir (not a git checkout)"
  fi
}

nu_config_dir() {
  nu -l -c '$nu.default-config-dir' | tail -n 1 | tr -d '\r'
}

nu_history_format() {
  nu -l -c '$env.config.history.file_format | into string' 2>/dev/null | tail -n 1 | tr -d '\r' || true
}

# Capture the pre-update configured history backend before pulling the new config,
# and before replacing the nu binary (a freshly installed nu can fail to start against
# a stale plugin registry, which would make detection return nothing).
# `history import` appends, so it must only ever run on a genuine plaintext -> sqlite
# switch. Anything other than a definite "plaintext" answer means: do not import.
pre_update_history_format="$(nu_history_format)"
log "Current Nushell history format: ${pre_update_history_format:-unknown}"

log "Installing/updating Nushell"
cargo binstall -y nu

run_git_pull "$HOME/nu"
run_git_pull "$HOME/nu_scripts"

install_carapace() {
  local os arch install_dir current_path carapace_version carapace_url tmpdir

  case "$(uname -s)" in
    Linux) os="linux" ;;
    Darwin) os="darwin" ;;
    *)
      log "Unsupported OS for Carapace binary install: $(uname -s)"
      return 1
      ;;
  esac

  case "$(uname -m)" in
    x86_64|amd64) arch="amd64" ;;
    arm64|aarch64) arch="arm64" ;;
    *)
      log "Unsupported architecture for Carapace binary install: $(uname -m)"
      return 1
      ;;
  esac

  # Prefer replacing an existing carapace on PATH. Otherwise choose a user-writable
  # location that is usually on PATH for the platform/config.
  current_path="$(command -v carapace || true)"
  if [[ -n "$current_path" && -w "$(dirname "$current_path")" ]]; then
    install_dir="$(dirname "$current_path")"
  elif [[ "$os" == "darwin" && -d /opt/homebrew/bin && -w /opt/homebrew/bin ]]; then
    install_dir="/opt/homebrew/bin"
  else
    install_dir="$HOME/.local/bin"
  fi
  mkdir -p "$install_dir"

  carapace_version="$(curl -fsSL https://api.github.com/repos/carapace-sh/carapace-bin/releases/latest | grep '"tag_name"' | sed 's/.*"v\([^"]*\)".*/\1/')"
  carapace_url="https://github.com/carapace-sh/carapace-bin/releases/download/v${carapace_version}/carapace-bin_${carapace_version}_${os}_${arch}.tar.gz"

  log "Downloading Carapace v${carapace_version} for ${os}/${arch} to ${install_dir}"
  tmpdir="$(mktemp -d)"
  curl -fsSL "$carapace_url" | tar -xz -C "$tmpdir" carapace
  install -m 0755 "$tmpdir/carapace" "$install_dir/carapace"
  rm -rf "$tmpdir"
}

log "Installing/updating Carapace"
install_carapace

run_git_pull "$HOME/owid-nushell"

# The shell integration below is generated by oh-my-posh itself, so an old oh-my-posh
# produces an old shim that newer nushell rejects (e.g. assigning the string
# $env.CMD_DURATION_MS to an int-typed `mut`). Keep oh-my-posh current alongside nu.
update_oh_my_posh() {
  local current_path brew_prefix install_dir
  current_path="$(command -v oh-my-posh || true)"

  if [[ -n "$current_path" ]] && command -v brew >/dev/null 2>&1; then
    brew_prefix="$(brew --prefix)"
    if [[ "$current_path" == "$brew_prefix"/* ]]; then
      log "Updating oh-my-posh via Homebrew"
      brew upgrade oh-my-posh || log "brew upgrade oh-my-posh failed; continuing with installed version"
      return 0
    fi
  fi

  if [[ -n "$current_path" && -w "$(dirname "$current_path")" ]]; then
    install_dir="$(dirname "$current_path")"
  else
    install_dir="$HOME/.local/bin"
  fi
  mkdir -p "$install_dir"

  log "Installing/updating oh-my-posh in $install_dir"
  curl -fsSL https://ohmyposh.dev/install.sh | bash -s -- -d "$install_dir" \
    || log "oh-my-posh install failed; continuing with installed version"
}

update_oh_my_posh

# The oh-my-posh shell integration is generated, not checked in: `oh-my-posh print`
# resolves the theme from $env.POSH_CONFIG / the session cache, so a shim generated by
# an older oh-my-posh silently falls back to the default theme. Regenerate it on every
# update so it can never go stale against a newer oh-my-posh.
generate_oh_my_posh_init() {
  local theme="$HOME/nu/utils/montys.omp.json"
  local out="$HOME/nu/utils/.oh-my-posh.nu"

  if ! command -v oh-my-posh >/dev/null 2>&1; then
    log "oh-my-posh not on PATH; skipping shell integration regeneration"
    return 0
  fi

  log "Regenerating oh-my-posh shell integration at $out"
  oh-my-posh init nu --config "$theme" --print \
    | sed \
        -e "s#\"$(command -v oh-my-posh)\"#\"oh-my-posh\"#" \
        -e "s#^\$env.POSH_CONFIG = \"$theme\"#\$env.POSH_CONFIG = \$\"(\$nu.home-dir)/nu/utils/montys.omp.json\"#" \
    > "$out.tmp"
  mv "$out.tmp" "$out"
}

# An old `oh-my-posh init nu` (without --print) dropped a shim into nushell's vendor
# autoload dir. It is loaded on every startup, is never regenerated, and now fails against
# current nushell (`$env.CMD_DURATION_MS` is a string, the old shim assigns it to an int).
# config.nu sources our generated integration, so the vendored copy is pure dead weight.
remove_stale_vendor_oh_my_posh() {
  local vendor_shim="$1/vendor/autoload/oh-my-posh.nu"
  if [[ -f "$vendor_shim" ]]; then
    log "Removing stale vendored oh-my-posh shim at $vendor_shim"
    rm -f "$vendor_shim"
  fi
}

# Each shell used to mint a fresh session id, leaving thousands of empty cache files behind.
prune_oh_my_posh_cache() {
  local cache_dir="$HOME/.cache/oh-my-posh"
  [[ -d "$cache_dir" ]] || return 0
  local stale
  stale="$(find "$cache_dir" -maxdepth 1 -name '*.omp.cache' -mtime +7 | wc -l | tr -d ' ')"
  if [[ "$stale" -gt 0 ]]; then
    log "Pruning $stale oh-my-posh session cache files older than 7 days"
    find "$cache_dir" -maxdepth 1 -name '*.omp.cache' -mtime +7 -delete
  fi
}

generate_oh_my_posh_init
prune_oh_my_posh_cache
remove_stale_vendor_oh_my_posh "$(nu_config_dir)"

post_update_history_format="$(nu_history_format)"
log "Nushell history format after config update: ${post_update_history_format:-unknown}"

config_dir="$(nu_config_dir)"
history_txt="$config_dir/history.txt"
history_marker="$config_dir/.history-migrated"

# Fail safe: import only on a definite plaintext -> sqlite transition, only once ever,
# and only when there is actually a plaintext file to import.
if [[ -f "$history_marker" ]]; then
  log "Plaintext history was already imported (marker $history_marker); skipping migration"
elif [[ "$pre_update_history_format" != "plaintext" ]]; then
  log "Pre-update history format was '${pre_update_history_format:-unknown}', not plaintext; skipping migration"
elif [[ "$post_update_history_format" != "sqlite" ]]; then
  log "History is not configured for sqlite after update; skipping migration"
elif [[ ! -f "$history_txt" ]]; then
  log "No plaintext history.txt found at $history_txt; skipping migration"
else
  history_backup="$history_txt.bak.$(date +%Y%m%d%H%M%S)"
  log "Backing up plaintext history to $history_backup"
  cp "$history_txt" "$history_backup"

  log "Importing plaintext history into sqlite history"
  nu -l -c 'history import'
  touch "$history_marker"
  log "History migration complete; marked as done at $history_marker"
fi
